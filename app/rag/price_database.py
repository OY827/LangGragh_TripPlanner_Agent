def get_price_by_name(city: str, name: str) -> tuple:
    """根据城市和景点名称获取票价"""
    if city == "北京":
        for key, value in BEIJING_PRICES.items():
            if key in name or name in key:
                return value
    elif city == "上海":
        for key, value in SHANGHAI_PRICES.items():
            if key in name or name in key:
                return value
    return None

def get_price_by_category(category: str, poi_type: str, name: str) -> tuple:
    """根据分类和类型获取票价"""
    category_rules = CATEGORY_PRICES.get(category, CATEGORY_PRICES["其他"])
    
    # 先检查景点名称中是否包含特定关键词
    for key, value in category_rules.items():
        if key in name:
            return value
    
    # 再检查POI类型中是否包含特定关键词
    for key, value in category_rules.items():
        if key in poi_type:
            return value
    
    # 返回默认值
    return category_rules["default"]

def get_attraction_price(city: str, name: str, category: str, poi_type: str) -> tuple:
    """获取景点票价和游览时长"""
    # 优先根据名称查找
    result = get_price_by_name(city, name)
    if result:
        return result
    
    # 其次根据分类和类型查找
    return get_price_by_category(category, poi_type, name)